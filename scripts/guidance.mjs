// Writes (or with --check, verifies) the generated skill reference from src/guidance/shared.ts.
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const TARGETS = [
  { src: "src/guidance/shared.ts", fn: "renderRulesReference", out: "plugin/skills/ask-righto-grounding/references/rules.md" },
  { src: "src/homeloans/guidance.ts", fn: "renderHomeLoanRulesReference", out: "plugin-internal/skills/home-loan-comparison/references/rules.md" },
];
let stale = false;

// Energy journeys: one source file each in src/guidance/energy/<journey>.md (frontmatter `description`, then the steps).
// Each writes its plugin skill, and all of them are written to journeys.generated.ts, which get_energy_guide serves.
const JOURNEY_DIR = "src/guidance/energy";
const journeys = readdirSync(resolve(ROOT, JOURNEY_DIR))
  .filter((n) => n.endsWith(".md"))
  .sort()
  .map((n) => {
    const text = readFileSync(resolve(ROOT, JOURNEY_DIR, n), "utf8");
    const m = /^---\ndescription: (.+)\n---\n\n?([\s\S]*)$/.exec(text);
    if (!m) throw new Error(`${JOURNEY_DIR}/${n} needs frontmatter with one description line`);
    return { id: n.replace(/\.md$/, ""), description: m[1], body: m[2].replace(/\s+$/, "") + "\n" };
  });
const skillFor = (j) => `---\nname: ${j.id}\ndescription: ${j.description}\n---\n<!-- Generated by \`npm run guidance:generate\` from ${JOURNEY_DIR}/${j.id}.md. Do not edit by hand. -->\n\n${j.body}`;
const journeysTs = () =>
  `// Generated by \`npm run guidance:generate\` from src/guidance/energy/*.md. Do not edit by hand.\nexport const ENERGY_JOURNEYS = ${JSON.stringify(Object.fromEntries(journeys.map((j) => [j.id, { description: j.description, body: j.body }])), null, 2)} as const;\n`;
const GENERATED = [
  ...journeys.map((j) => ({ out: `plugin/skills/${j.id}/SKILL.md`, text: skillFor(j), dir: `plugin/skills/${j.id}` })),
  { out: `${JOURNEY_DIR}/journeys.generated.ts`, text: journeysTs() },
];
for (const g of GENERATED) {
  const target = resolve(ROOT, g.out);
  if (process.argv.includes("--check")) {
    let actual = "";
    try { actual = readFileSync(target, "utf8"); } catch { /* missing */ }
    if (actual !== g.text) { console.error(`${g.out} is stale: run \`npm run guidance:generate\``); stale = true; }
  } else {
    if (g.dir) mkdirSync(resolve(ROOT, g.dir), { recursive: true });
    writeFileSync(target, g.text);
  }
}

for (const t of TARGETS) {
  const out = await build({ entryPoints: [resolve(ROOT, t.src)], bundle: true, write: false, format: "esm", platform: "node", logLevel: "warning" });
  const mod = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString("base64")}`);
  const expected = mod[t.fn]();
  const target = resolve(ROOT, t.out);
  if (process.argv.includes("--check")) {
    let actual = "";
    try { actual = readFileSync(target, "utf8"); } catch { /* missing */ }
    if (actual !== expected) { console.error(`${t.out} is stale: run \`npm run guidance:generate\``); stale = true; }
  } else writeFileSync(target, expected);
}
if (stale) process.exit(1);
