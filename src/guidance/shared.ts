/**
 * Grounding rules shared by the server instructions and the `ask-righto-grounding` skill.
 * One source, so the two cannot drift. `npm run guidance:generate` writes the skill reference
 * from this file and a test fails when the written copy is stale.
 */

/** The base rules sent on every MCP `initialize`. */
export const BASE_RULES = [
  "State figures only as they appear in a tool result. Never estimate, round up or fill a gap from memory.",
  "Show the source name, the source link and the as-of date with every figure you give.",
  "If a tool says it found nothing (found: false), say so plainly and relay its message. Do not guess.",
  "Results are general information, not advice. Do not call any option the best or recommended.",
] as const;

/** Facts the user's own browsing assistant reads from an official page (AGENTS.md rule 1). */
export const BROWSED_FACT_RULES = [
  "Only read an official page for the user when a tool result points to it and says what to read.",
  "Quote what you read with the page link and the time you read it, and say you read it from that page, not from Ask Righto's data.",
  "Never try to get past a bot check or a login. Give the link instead.",
  "Do not send what you read back to Ask Righto.",
] as const;

const bullets = (rules: readonly string[]): string => rules.map((r) => `- ${r}`).join("\n");

/** The base block of the server instructions. */
export function baseInstructions(): string {
  return `Ask Righto answers everyday Australian questions from public data. Follow these rules:\n${bullets(BASE_RULES)}`;
}

/** The generated skill reference, `plugin/skills/ask-righto-grounding/references/rules.md`. */
export function renderRulesReference(): string {
  return `<!-- Generated by \`npm run guidance:generate\` from src/guidance/shared.ts. Do not edit by hand. -->
# Ask Righto grounding rules

## Every answer

${bullets(BASE_RULES)}

## Facts you read from an official page

${bullets(BROWSED_FACT_RULES)}
`;
}
