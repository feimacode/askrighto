/**
 * split-energy-host-guidance: one source per journey served two ways, size budgets on always-loaded guidance, and
 * results that name the next step. No database needed.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { ENERGY_INSTRUCTIONS } from "../../src/energy/instructions.js";
import { nextStepsFor, NEXT_STEP_MAX, type CurrentPlan } from "../../src/energy/compare/rank.js";
import { JOURNEY_IDS, journeyBody, journeyDescription } from "../../src/guidance/energy/index.js";
import { allTools } from "../../src/tools/index.js";
import { energyVertical } from "../../src/energy/vertical.js";
import { getEnergyGuide } from "../../src/tools/get-energy-guide.js";

const ROOT = resolve(import.meta.dirname, "../..");
const SKILLS = join(ROOT, "plugin/skills");
const DESCRIPTION_MAX = 500;
const INSTRUCTIONS_MAX = 1500;

describe("journey sources", () => {
  it("has one source file, one generated skill and one guide entry per journey", () => {
    const sources = readdirSync(join(ROOT, "src/guidance/energy")).filter((n) => n.endsWith(".md")).map((n) => n.replace(/\.md$/, "")).sort();
    expect(sources).toEqual([...JOURNEY_IDS].sort());
    for (const id of JOURNEY_IDS) {
      const skill = readFileSync(join(SKILLS, id, "SKILL.md"), "utf8");
      expect(skill).toContain(journeyBody(id).trim());
      expect(skill).toMatch(new RegExp(`^---\\nname: ${id}\\ndescription: `));
      expect(skill).toContain(`Generated by \`npm run guidance:generate\` from src/guidance/energy/${id}.md`);
      expect(journeyDescription(id).length).toBeGreaterThan(40);
    }
  });

  it("no longer ships the single energy-bill-comparison skill", () => {
    expect(existsSync(join(SKILLS, "energy-bill-comparison"))).toBe(false);
    expect(readdirSync(SKILLS).sort()).toEqual(["ask-righto-grounding", ...JOURNEY_IDS].sort());
  });

  it("fails guidance:check when a generated skill drifts from its source", () => {
    const run = () => execFileSync("node", ["scripts/guidance.mjs", "--check"], { cwd: ROOT, stdio: "pipe" });
    expect(run).not.toThrow();
  });

  it("names only tools that exist, and states no price", () => {
    const names = new Set([...allTools, ...energyVertical.tools].map((t) => t.name));
    for (const id of JOURNEY_IDS) {
      const text = journeyBody(id);
      for (const m of text.matchAll(/`((?:get|search|compare|list|summarise)_[a-z_]+)`/g)) expect(names.has(m[1]!), `${id}: ${m[1]}`).toBe(true);
      expect(text, id).not.toMatch(/\$\s?\d|\b\d+(\.\d+)?\s?(cents|c\/kWh)\b/i);
      expect(text, id).not.toMatch(/\b(Claude|ChatGPT|OpenAI|Gemini|Anthropic)\b/i);
    }
  });

  it("keeps each journey short enough to load on demand", () => {
    for (const id of JOURNEY_IDS) expect(journeyBody(id).length, id).toBeLessThan(id === "energy-readings" ? 5000 : 3500);
  });
});

describe("get_energy_guide", () => {
  it("returns the same steps as the skill of that name, for every journey", async () => {
    for (const id of JOURNEY_IDS) {
      const r = (await getEnergyGuide.handler({ journey: id } as never)) as { found: true; data: { steps: string; journey: string; notice: string }; source: { name: string }; asOf: string };
      expect(r.found).toBe(true);
      expect(r.data.journey).toBe(id);
      const skill = readFileSync(join(SKILLS, id, "SKILL.md"), "utf8");
      expect(skill.endsWith(r.data.steps)).toBe(true);
      expect(getEnergyGuide.render!(r.data as never, r as never)).toContain(r.data.steps);
      expect(r.asOf).toBeTruthy();
    }
  });
  it("is read-only and takes only the journey", () => {
    expect(getEnergyGuide.readOnlyHint).toBe(true);
    expect(getEnergyGuide.destructiveHint).toBe(false);
    expect(Object.keys(getEnergyGuide.inputSchema.shape)).toEqual(["journey"]);
    expect(() => getEnergyGuide.inputSchema.parse({ journey: "energy-everything" })).toThrow();
  });
  it("is registered on the energy vertical", () => {
    expect(energyVertical.tools.map((t) => t.name)).toContain("get_energy_guide");
  });
});

describe("size budgets", () => {
  it(`keep every energy tool description to ${DESCRIPTION_MAX} characters, with no steps`, () => {
    const energy = energyVertical.tools;
    expect(energy.length).toBeGreaterThanOrEqual(8);
    for (const t of energy) {
      expect(t.description.length, `${t.name}: ${t.description.length} characters`).toBeLessThanOrEqual(DESCRIPTION_MAX);
      expect(t.description, t.name).not.toMatch(/\b(first|then|next|step \d|\(1\)|1\.)\b.*\b(second|then|finally|\(2\)|2\.)\b/i);
    }
  });
  it(`keeps the energy server instructions to ${INSTRUCTIONS_MAX} characters`, () => {
    expect(ENERGY_INSTRUCTIONS.length).toBeLessThanOrEqual(INSTRUCTIONS_MAX);
  });
  it("points to the guide and to each journey from the instructions", () => {
    expect(ENERGY_INSTRUCTIONS).toMatch(/get_energy_guide/);
    for (const id of JOURNEY_IDS) expect(ENERGY_INSTRUCTIONS).toContain(id);
  });
});

describe("nextSteps", () => {
  const none: CurrentPlan = { costed: false, reason: "no_current_plan", detail: "No current plan was given." };
  const base = { elec: true, hasSplit: false, touNotEstimated: 0, current: none, verified: true };
  it("offers the split or readings for a bill or yearly figure that left time-of-use plans out", () => {
    for (const level of ["bill", "yearly"] as const) {
      expect(nextStepsFor({ ...base, level, touNotEstimated: 3 }).join(" ")).toMatch(/peak, shoulder and off-peak split/);
      expect(nextStepsFor({ ...base, level, hasSplit: true, touNotEstimated: 0 }).join(" ")).not.toMatch(/peak, shoulder and off-peak split/);
    }
  });
  it("offers readings after a single bill, a bill after typical usage, and verified readings after assistant_readings", () => {
    expect(nextStepsFor({ ...base, level: "bill" }).join(" ")).toMatch(/summarise_interval_readings/);
    expect(nextStepsFor({ ...base, level: "yearly" }).join(" ")).not.toMatch(/summarise_interval_readings/);
    expect(nextStepsFor({ ...base, level: "typical" }).join(" ")).toMatch(/bill or interval readings/);
    expect(nextStepsFor({ ...base, level: "assistant_readings" }).join(" ")).toMatch(/verified by Ask Righto/);
    expect(nextStepsFor({ ...base, level: "readings" })).toEqual(expect.not.arrayContaining([expect.stringMatching(/summarise_interval_readings/)]));
  });
  it("offers the current plan when none was given, and explains a baseline that was not costed", () => {
    expect(nextStepsFor({ ...base, level: "yearly" }).join(" ")).toMatch(/list_current_plan_options/);
    const nc: CurrentPlan = { costed: false, reason: "not_estimated", planId: "X", detail: "x" };
    expect(nextStepsFor({ ...base, level: "typical", current: nc }).join(" ")).toMatch(/current plan was not costed/);
  });
  it(`keeps every step to ${NEXT_STEP_MAX} characters and carries no recipe`, () => {
    for (const level of ["readings", "assistant_readings", "bill", "yearly", "typical"] as const) {
      for (const current of [none, { costed: false, reason: "not_estimated", planId: "X", detail: "x" } as CurrentPlan]) {
        for (const s of nextStepsFor({ ...base, level, hasSplit: false, touNotEstimated: 2, current })) {
          expect(s.length, s).toBeLessThanOrEqual(NEXT_STEP_MAX);
          expect(s).not.toMatch(/\bNEM12\b|\b200 record\b/);
        }
      }
    }
  });
});
